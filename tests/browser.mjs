import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {readFile,mkdir} from 'node:fs/promises';
import {deflateRawSync} from 'node:zlib';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE_PATH?pathToFileURL(process.env.PLAYWRIGHT_MODULE_PATH).href:'playwright');
const port=45173,origin=`http://127.0.0.1:${port}`;
const server=spawn(process.execPath,['scripts/serve.mjs'],{cwd:root,env:{...process.env,PORT:String(port)},stdio:'pipe'});
let browser;
try {
  await new Promise((resolve,reject)=>{server.stdout.once('data',resolve);server.once('error',reject);server.once('exit',code=>reject(new Error('Server exited: '+code)));});
  browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{}),args:['--no-sandbox']});
  const context=await browser.newContext({permissions:['clipboard-read','clipboard-write']});
  const page=await context.newPage();const errors=[];const external=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.route('**/*',route=>{if(route.request().url().startsWith(origin))route.continue();else{external.push(route.request().url());route.abort();}});
  await page.goto(origin);await page.getByRole('button',{name:'Prova con il diagramma di esempio'}).click();
  await page.waitForFunction(()=>!document.getElementById('copy').disabled);
  assert.match(await page.locator('#stats').textContent(),/5 forme/);
  assert.equal(await page.locator('#arrows').isChecked(),false);
  await page.locator('#copy').click();
  const copied=await page.evaluate(async()=>{for(const item of await navigator.clipboard.read())if(item.types.includes('text/html'))return(await item.getType('text/html')).text();});
  assert(copied.includes('whiteboardcontent='));
  const payload=JSON.parse(decodeURIComponent(copied.match(/whiteboardcontent="([^"]+)"/)[1]));
  assert.equal(payload.boardItems.length,7);assert(payload.boardItems.every(i=>i.content.contentType==='shape'));
  await page.locator('#arrows').check();assert.match(await page.locator('#stats').textContent(),/oggetti generati/);
  assert(await page.locator('#preview rect').count()>30);
  const downloadPromise=page.waitForEvent('download');await page.locator('#script').click();
  const download=await downloadPromise;assert.equal(download.suggestedFilename(),'drawioToMsWhiteboard.txt');
  const script=await readFile(await download.path(),'utf8');assert(script.includes('Copia solo forme e testi'));
  await mkdir(path.join(root,'test-results'),{recursive:true});
  await page.screenshot({path:path.join(root,'test-results','desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(root,'test-results','mobile.png'),fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.setViewportSize({width:1280,height:900});
  const basic=await readFile(path.join(root,'examples/basic.drawio'),'utf8');
  const graph=basic.match(/<mxGraphModel>[\s\S]*<\/mxGraphModel>/)[0];
  const compressed=deflateRawSync(Buffer.from(encodeURIComponent(graph))).toString('base64');
  const multi=`<mxfile><diagram name="Prima">${compressed}</diagram><diagram name="Seconda">${graph}</diagram></mxfile>`;
  await page.locator('#file').setInputFiles({name:'compressed.drawio',mimeType:'application/xml',buffer:Buffer.from(multi)});
  await page.waitForFunction(()=>!document.getElementById('copy').disabled);
  assert.equal(await page.locator('#page option').count(),2);
  await page.locator('#page').selectOption('1');await page.waitForFunction(()=>!document.getElementById('copy').disabled);
  assert.match(await page.locator('#stats').textContent(),/5 forme/);
  // Labels are treated as inert text, even if they contain HTML-looking content.
  const injection='<mxGraphModel><root><mxCell id="a" vertex="1" value="&amp;lt;img src=x onerror=alert(1)&amp;gt;" style=""><mxGeometry x="0" y="0" width="250" height="100"/></mxCell></root></mxGraphModel>';
  await page.locator('#file').setInputFiles({name:'text.xml',mimeType:'application/xml',buffer:Buffer.from(injection)});
  await page.waitForFunction(()=>!document.getElementById('copy').disabled);assert.equal(await page.locator('#preview img').count(),0);
  assert((await page.locator('#preview text').textContent()).includes('<img'));
  await page.locator('#file').setInputFiles({name:'broken.drawio',mimeType:'application/xml',buffer:Buffer.from('<broken>')});
  await page.waitForFunction(()=>document.getElementById('status').classList.contains('error'));
  assert(await page.locator('#copy').isDisabled());
  assert.deepEqual(external,[]);assert.deepEqual(errors,[]);
  console.log('Browser OK: demo, appunti HTML, frecce opzionali, script, mobile, XML compresso, pagine multiple, testo inerte, XML non valido.');
} finally {await browser?.close();server.kill();}
